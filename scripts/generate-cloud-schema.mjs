import { mkdtempSync, mkdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const temp = mkdtempSync(join(tmpdir(), 'jlpt-empty-schema-'));
process.env.JLPT_DB_PATH = join(temp,'empty.sqlite');
process.env.JLPT_REVIEW_DATA_PATH = join(temp,'empty-seeds');
mkdirSync(process.env.JLPT_REVIEW_DATA_PATH);
const { getDb } = await import('../server/storage.mjs');
const { listShares } = await import('../server/market.mjs');
const { createJlptMcp } = await import('../server/mcp-app.mjs');
const db=getDb();
listShares(0);
await createJlptMcp({onEvent(){}}).ensureSchema();
db.exec('CREATE TABLE IF NOT EXISTS firebase_identities (project_id TEXT NOT NULL, uid TEXT NOT NULL, user_id INTEGER NOT NULL REFERENCES users(id), PRIMARY KEY(project_id,uid))');
const records=db.prepare("SELECT type,name,sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 WHEN 'view' THEN 2 ELSE 3 END, rowid").all();
const sql=records.map(r=>r.sql.replace(/[ \t]+$/gm,'')+';').join('\n\n')+'\nINSERT OR IGNORE INTO mcp_read_revision(id,revision) VALUES(1,0);\n';
writeFileSync('cloudflare/migrations/0001.sql', '-- Generated from a new, empty local database. No personal data.\n'+sql);
console.log('Cloud schema created; users:',db.prepare('SELECT count(*) AS n FROM users').get().n,'items:',db.prepare('SELECT count(*) AS n FROM review_items').get().n);
db.close();
